async def _claude_deltas(run):
    "Normalize one ClaudeRun turn to FastLLM deltas"
    reindex = _reidx()
    blocks = _ToolBlocks()
    async for m in run:
        if m.get('type')!='stream_event': continue
        ev = reindex(m['event'])
        d = norm_sse_event(ev)
        for tc in (d.tool_calls or []): tc.name = unqual(tc.name)
        yield d
        if extra := blocks.observe(ev, d): yield extra

