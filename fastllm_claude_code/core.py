async def claude_oauth_exchange(oauth, code):
    "Exchange a pasted callback `code` (`code` or `code#state`) for a Claude auth dictionary"
    auth_code, _, pasted_state = (code or '').strip().partition('#')
    if not auth_code: raise ValueError('Paste the code shown after signing in to Claude')
    if pasted_state and pasted_state != oauth['state']: raise ValueError('Sign-in state mismatch; open the sign-in link again')
    body = dict(grant_type='authorization_code', code=auth_code, redirect_uri=f'{_PLATFORM}/oauth/code/callback',
        client_id=_CLIENT_ID, code_verifier=oauth['code_verifier'], state=oauth['state'], expires_in=_TOKEN_TTL)
    async with httpx2.AsyncClient() as cli: r = await cli.post(f'{_PLATFORM}/v1/oauth/token', json=body)
    if r.is_error:
        d = r.json() if 'json' in r.headers.get('content-type', '') else {}
        raise ValueError(d.get('error_description') or d.get('error') or f'Claude sign-in failed (HTTP {r.status_code})')
    return claude_auth(r.json().get('access_token'))
