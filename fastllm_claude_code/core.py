def claude_norm_completion(comp, msgs):
    "Keep native results and replay data on final completions; pass other parts through"
    if not isinstance(comp, Completion): return comp
    results = {p.id:p.text for m in msgs if m.role=='tool' for p in m.content}
    for tc in comp.tool_calls:
        if tc.server: tc.text = results.get(tc.id, tc.text)
    comp.message.raw,comp.message.raw_api = [m.raw for m in msgs],'claude_code'
    return comp


async def claude_acollect_stream(payload, **kwargs):
    "Adapt one `ClaudeRun` to FastLLM"
    run = astream(**payload)
    try:
        async for o in mk_acollect_stream(_claude_deltas(run), index_fn=delta_index_fn, api_name='claude_code', **kwargs):
            yield claude_norm_completion(o, run.messages)
    except FileNotFoundError as e: raise APIError(str(e), provider='claude_code', model=payload.get('model'), retryable=False) from e
    _check_run(run, payload)

