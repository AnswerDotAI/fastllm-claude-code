async def _claude_deltas(run):
    "Normalize one ClaudeRun turn to FastLLM deltas"
    reindex = _reidx()
    blocks = _ToolBlocks()
    async for m in run:
        if m.get('type')!='stream_event': continue
        ev = reindex(m['event'])
        d = norm_sse_event(ev)
        extra = blocks.observe(ev, d, run.native_tools)
        yield d
        if extra: yield extra

