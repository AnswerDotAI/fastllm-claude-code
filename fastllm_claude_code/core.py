_CLIENT_ID = '9d1c250a-e61b-44d9-88ed-5944d1962f5e'
_AUTH = 'https://claude.com/cai/oauth/authorize'
_PLATFORM = 'https://platform.claude.com'
_TOKEN_TTL = 365*24*3600

def _pkce_challenge(verifier): return base64.urlsafe_b64encode(hashlib.sha256(verifier.encode()).digest()).rstrip(b'=').decode()

def claude_oauth_start():
    "Start a Claude Code OAuth PKCE sign-in, returning `url`, `code_verifier`, and `state`"
    verifier, state = secrets.token_urlsafe(32), secrets.token_urlsafe(32)
    qs = urlencode(dict(code='true', client_id=_CLIENT_ID, response_type='code', redirect_uri=f'{_PLATFORM}/oauth/code/callback',
        scope='user:inference', code_challenge=_pkce_challenge(verifier), code_challenge_method='S256', state=state))
    return dict(url=f'{_AUTH}?{qs}', code_verifier=verifier, state=state)

